use dope_quic::security::crypto::sha256::{self, Prk};

#[test]
fn preserves_identity_keys() {
    let root = Prk::try_extract(b"lsd/egress/identity/v1", &[7; 32]).expect("extract");
    let mut output = [0; 32];
    root.try_expand(b"lsd/egress/signing/v1", &mut output)
        .expect("signing key");
    assert_eq!(
        output,
        [
            0xb6, 0xc4, 0x9d, 0x8a, 0x6e, 0xf0, 0xfb, 0xd1, 0x6f, 0x97, 0x44, 0xd6, 0xb8, 0x7e,
            0x27, 0x8c, 0x37, 0x33, 0x63, 0xf5, 0x9d, 0x79, 0xac, 0x50, 0x17, 0x93, 0x84, 0xab,
            0xe3, 0xf7, 0xe7, 0x1a,
        ]
    );
    root.try_expand(b"lsd/egress/stateless-reset/v1", &mut output)
        .expect("reset key");
    assert_eq!(
        output,
        [
            0xad, 0x7a, 0xad, 0x5a, 0xd4, 0x56, 0x2e, 0x93, 0xa4, 0x50, 0xf8, 0xf1, 0x52, 0x7b,
            0x0a, 0xd9, 0xbf, 0x82, 0x43, 0x37, 0x32, 0x27, 0xb5, 0x01, 0x47, 0x51, 0xa0, 0xa6,
            0x9f, 0xce, 0xeb, 0x22,
        ]
    );
}

#[test]
fn admits_long_salt_and_full_context() {
    let salt = std::array::from_fn::<_, 256, _>(|index| index as u8);
    let root = Prk::try_extract(&salt, &[7; 32]).expect("long salt");
    let mut output = [0; 32];
    root.try_expand(&[0xa5; 80], &mut output)
        .expect("full context");
    assert_eq!(
        output,
        [
            0x86, 0x9e, 0xd0, 0xd6, 0x7c, 0x3e, 0x11, 0x0d, 0xb5, 0x41, 0xbb, 0x46, 0x4a, 0x47,
            0xb6, 0x05, 0x3c, 0x49, 0x19, 0x6f, 0x4f, 0xd6, 0xd7, 0xe5, 0x6c, 0x61, 0x11, 0x5b,
            0xa5, 0xbf, 0x70, 0x47,
        ]
    );
}

#[test]
fn hashes_one_shot() {
    assert_eq!(
        sha256::digest(b"abc"),
        [
            0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae,
            0x22, 0x23, 0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61,
            0xf2, 0x00, 0x15, 0xad,
        ]
    );
}
